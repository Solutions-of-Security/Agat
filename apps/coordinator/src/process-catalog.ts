/** Return independent data so callers cannot mutate the built-in source of truth. */
export function getProcessTemplateCatalog(): ProcessTemplateCatalog {
  return structuredClone({ version: 1, categories, templates });
}

export function instantiateCatalogTemplate(
  id: unknown,
  version: unknown,
  bindings: unknown,
  knownAgentIds: Set<string>,
): { template: ProcessTemplate; graph: ProcessGraph } {
  if (typeof id !== "string") throw new Error("ID шаблона каталога должен быть строкой");
  const source = templates.find((template) => template.id === id);
  if (!source) throw new Error("Шаблон каталога не найден");
  if (version !== source.version) throw new Error("Версия шаблона изменилась или не указана. Обновите каталог");
  if (bindings !== undefined && (!bindings || typeof bindings !== "object" || Array.isArray(bindings))) {
    throw new Error("Назначения агентов должны быть объектом");
  }
  const roleIds = new Set(source.roles.map((role) => role.id));
  const assignments = new Map<string, string>();
  for (const [roleId, agentId] of Object.entries(bindings ?? {})) {
    if (!roleIds.has(roleId)) throw new Error(`Неизвестная роль шаблона: ${roleId}`);
    if (typeof agentId !== "string" || !agentId.trim() || !knownAgentIds.has(agentId)) {
      throw new Error(`Роль ${roleId}: агент не найден в проекте`);
    }
    assignments.set(roleId, agentId);
  }
  const template = structuredClone(source);
  const graph = structuredClone(source.graph);
  for (const stage of source.stages) {
    const agentId = assignments.get(stage.roleId);
    if (agentId) graph.nodes.find((node) => node.id === stage.id)!.config.agentId = agentId;
  }
  return { template, graph };
}
