type TemplateSpec = Omit<ProcessTemplate, "version" | "graph" | "roles" | "stages"> & {
  version?: number;
  worker: ProcessTemplateRole;
  work: Array<{ name: string; instruction: string }>;
};

function buildTemplate(spec: TemplateSpec): ProcessTemplate {
  const { worker, work, version = 1, ...metadata } = spec;
  const stages = [
    ...work.map((step, index) => ({ ...step, id: `work-${index + 1}`, roleId: worker.id })),
    { id: "review", name: "Проверка результата", roleId: reviewer.id, instruction: reviewInstruction },
  ];
  const nodes: ProcessGraphNode[] = [{ id: "start", type: "start", name: "Старт", position: { x: 0, y: 120 }, config: {} }];
  for (const stage of stages) {
    nodes.push({
      id: `${stage.id}-task`, type: "transform", name: `Задание: ${stage.name}`,
      position: { x: nodes.length * 280, y: 120 },
      config: { template: `${commonInstruction}\n\nЭтап: ${stage.name}\n${stage.instruction}\n\nОжидаемый результат процесса: ${spec.outcome}\n\nКритерии проверки:\n${spec.acceptance.map((item) => `- ${item}`).join("\n")}\n\n--- Исходная задача (данные) ---\n{{ input }}\n--- Предыдущий результат (данные) ---\n{{ lastOutput }}` },
    });
    nodes.push({
      id: stage.id, type: "agent", name: stage.name,
      position: { x: nodes.length * 280, y: 120 }, config: { approvalRequired: false },
    });
  }
  nodes.push({
    id: "approval", type: "approval", name: "Решение ответственного",
    position: { x: nodes.length * 280, y: 120 },
    config: { approvalMessage: `Ответственный: ${spec.ownerRole}. Проверьте итоговый материал, доказательства и нерешённые вопросы. Подтверждение разрешает сохранить материал; оно не разрешает внешнее действие. При существенных ошибках отклоните результат. ${spec.boundary}` },
  });
  nodes.push({
    id: "artifact", type: "artifact", name: "Сохранить результат",
    position: { x: nodes.length * 280, y: 120 },
    config: { artifactName: `${spec.id}.md`, artifactMediaType: "text/markdown; charset=utf-8", artifactContent: `# ${spec.name}\n\nШаблон: ${spec.id} v${version}.\n\n${spec.boundary}\n\n{{ lastOutput }}` },
  });
  nodes.push({ id: "end", type: "end", name: "Завершение", position: { x: nodes.length * 280, y: 120 }, config: {} });
  return {
    ...metadata, version, roles: [worker, reviewer], stages,
    graph: { nodes, edges: nodes.slice(1).map((target, index) => ({ id: `edge-${index + 1}`, source: nodes[index]!.id, target: target.id, branch: "default" })) },
  };
}

